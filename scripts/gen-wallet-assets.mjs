// Generates the Apple Wallet pass images from the brand marks and writes them as
// base64 into src/lib/apple-wallet-assets.ts. Embedding (rather than fs-reading
// public/ at runtime) is deliberate: Vercel serverless functions don't reliably
// have public/ on disk, so a .pkpass built in a function needs its images inlined.
//
//   node scripts/gen-wallet-assets.mjs
import sharp from "sharp";
import { writeFileSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const MARK = join(ROOT, "public/logos/mgz-mark.png");
const WORDMARK = join(ROOT, "public/logos/madgigz-wordmark.png");

async function pngB64(src, opts) {
  const buf = await sharp(src).resize(opts).png().toBuffer();
  return buf.toString("base64");
}

// Icons are square (contain, transparent). Logo keeps aspect at a fixed height.
const assets = {
  ICON: await pngB64(MARK, { width: 29, height: 29, fit: "contain", background: { r: 0, g: 0, b: 0, alpha: 0 } }),
  ICON_2X: await pngB64(MARK, { width: 58, height: 58, fit: "contain", background: { r: 0, g: 0, b: 0, alpha: 0 } }),
  ICON_3X: await pngB64(MARK, { width: 87, height: 87, fit: "contain", background: { r: 0, g: 0, b: 0, alpha: 0 } }),
  LOGO: await pngB64(WORDMARK, { height: 40, fit: "inside", background: { r: 0, g: 0, b: 0, alpha: 0 } }),
  LOGO_2X: await pngB64(WORDMARK, { height: 80, fit: "inside", background: { r: 0, g: 0, b: 0, alpha: 0 } }),
};

const header = `// AUTO-GENERATED by scripts/gen-wallet-assets.mjs — do not edit by hand.
// Apple Wallet pass images (#129 wallet), base64-encoded PNGs so a .pkpass built
// in a serverless function has its images without reading public/ from disk.
// Regenerate after changing the brand marks: node scripts/gen-wallet-assets.mjs
`;
const body = Object.entries(assets)
  .map(([k, v]) => `export const ${k} = "${v}";`)
  .join("\n");

writeFileSync(join(ROOT, "src/lib/apple-wallet-assets.ts"), `${header}\n${body}\n`);
console.log("Wrote src/lib/apple-wallet-assets.ts");
for (const [k, v] of Object.entries(assets)) {
  console.log(`  ${k}: ${Math.round((v.length * 3) / 4)} bytes`);
}
